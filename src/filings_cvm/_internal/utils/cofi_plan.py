# (nature, parent, start, end) per account code; ``end`` is None while in force.
PlanAccount = tuple[str, str, date, date | None]


@type_checker
def _parse_iso(compact: str) -> date | None:
	"""Parse a compact ``YYYYMMDD`` date, ``""`` meaning no date.

	Parameters
	----------
	compact : str
		The compact date or the empty string.

	Returns
	-------
	date or None
		The parsed date, or ``None`` for the empty string.
	"""
	if not compact:
		return None
	return date(int(compact[:4]), int(compact[4:6]), int(compact[6:]))


@type_checker
def _load_plan() -> dict[str, PlanAccount]:
	"""Build the code -> account mapping from the transcribed rows.

	Returns
	-------
	dict[str, PlanAccount]
		Every COFI account keyed by its 8-character code.
	"""
	plan: dict[str, PlanAccount] = {}
	for line in _PLAN_ROWS.strip().splitlines():
		code, nature, parent, start, end = line.strip().split(",")
		plan[code] = (nature, parent, _parse_iso(start), _parse_iso(end))
	return plan


COFI_PLAN: dict[str, PlanAccount] = _load_plan()
